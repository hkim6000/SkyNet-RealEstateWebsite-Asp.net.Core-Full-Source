        private async Task<View> Render(SiteData site)
        {
            string area = Q("area", 40);
            List<Models.Area> areas = site.Areas.Where(a => a.Active).OrderBy(a => a.Order).ToList();
            if (!areas.Any(a => a.Key == area))
            {
                area = string.Empty;
            }
            List<TeamMember> team = site.Agents.Where(a => a.Active && (area == string.Empty || a.Areas.Contains(area))).OrderBy(a => a.Order).ToList();
            string word = site.Settings.AgentsWord;
            StringBuilder sb = new StringBuilder("<section class=\"ag-phead ag-wrap\"><span class=\"ag-kick\">Our team</span><h1>" + Ui.Enc(word) + " who live where they sell</h1><p class=\"ag-lead\">Each of us covers two neighborhoods, so the person you talk to knows the streets, the schools and what homes really sell for.</p></section>");
            sb.Append("<div class=\"ag-wrap\"><nav class=\"ag-chips ag-afil\" aria-label=\"Filter by neighborhood\"><a class=\"ag-chip" + (area == string.Empty ? " ag-act" : string.Empty) + "\" href=\"Agents\">Everyone</a>");
            foreach (Models.Area a in areas)
            {
                sb.Append("<a class=\"ag-chip" + (a.Key == area ? " ag-act" : string.Empty) + "\" href=\"Agents?area=" + Uri.EscapeDataString(a.Key) + "\"><i style=\"background:" + (Ui.SafeColor(a.Color) ? a.Color : "#B5562F") + "\"></i>" + Ui.Enc(a.Name) + "</a>");
            }
            sb.Append("</nav><div class=\"ag-team\">");
            foreach (TeamMember a in team)
            {
                int live = site.Listings.Count(l => l.Agent == a.Id && Ui.Live(l));
                int sold = site.Listings.Count(l => l.Agent == a.Id && l.Status is "sold" or "rented");
                string href = "Agent?id=" + Uri.EscapeDataString(a.Id);
                string tel = Regex.Replace(a.Phone, "[^0-9+]", string.Empty);
                sb.Append("<article class=\"ag-tc\"><a href=\"" + href + "\" class=\"ag-tc-img\" tabindex=\"-1\" aria-hidden=\"true\">" + Ui.Face("ag", a) + "</a><div class=\"ag-tc-b\"><h2><a href=\"" + href + "\">" + Ui.Enc(a.Name) + "</a></h2><p class=\"ag-tc-t\">" + Ui.Enc(a.Title) + " &middot; " + Ui.Plural(a.Years, "year", "years") + "</p><p class=\"ag-tc-a\">" + Ui.Enc(string.Join(" & ", a.Areas.Select(k => Ui.AreaName(site, k)))) + "</p><p class=\"ag-tc-l\">Speaks " + Ui.Enc(string.Join(", ", a.Languages)) + "</p><div class=\"ag-tc-n\"><span><b>" + live + "</b> listed</span><span><b>" + sold + "</b> recently closed</span></div><div class=\"ag-tc-c\"><a class=\"ag-btn ag-btn-ghost ag-btn-sm\" href=\"tel:" + Ui.Attr(tel) + "\"><svg viewBox=\"0 0 24 24\" width=\"18\" height=\"18\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"1.8\" stroke-linejoin=\"round\" aria-hidden=\"true\"><path d=\"M6.5 3.5h3l1.5 4.5-2 1.5a11 11 0 0 0 5.5 5.5l1.5-2 4.5 1.5v3a2 2 0 0 1-2 2A16 16 0 0 1 4.5 5.5a2 2 0 0 1 2-2z\"/></svg> " + Ui.Enc(a.Phone) + "</a><a class=\"ag-btn ag-btn-sm\" href=\"" + href + "\">Profile</a></div></div></article>");
            }
            if (team.Count == 0)
            {
                sb.Append("<p class=\"ag-none\">Nobody covers this neighborhood right now. Call the office on " + Ui.Enc(site.Settings.Phone) + ".</p>");
            }
            sb.Append("</div></div>");
            return new View { Title = word, Desc = "Meet the " + word.ToLowerInvariant() + " of " + site.Settings.Name + " in " + site.Settings.Town + ".", Main = sb.ToString(), Nav = "agents" };
        }
